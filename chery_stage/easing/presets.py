def get_presets_by_category(category: str) -> List[Dict[str, Any]]:
    """Filter presets by selected category."""
    if category == "ALL":
        return list(PRESETS.values())
    if category in ("IN", "OUT", "IN_OUT"):
        return [p for p in PRESETS.values() if p.get("ease_type") == category]
    return [p for p in PRESETS.values() if p.get("category") == category]
